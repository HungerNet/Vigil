#!/usr/bin/env python3
"""Compile Vigil's Java shim classes and embed them as C++ headers.

Usage: python tools/build_java.py [--javac PATH]

Compiles java/src/*.java against java/stubs (Java 8 bytecode, the version Lunar 1.8.9 loads) and
writes src/game/bytecode/<Class>.h containing `k<Class>Bytes` / `k<Class>Size`. The generated
headers are committed so the native build does not need a JDK.
"""

from __future__ import annotations

import argparse
import os
import pathlib
import shutil
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parents[1]
SRC = ROOT / "java" / "src"
STUBS = ROOT / "java" / "stubs"
OUT = ROOT / "src" / "game" / "bytecode"


def find_javac(explicit: str | None) -> str:
    if explicit:
        return explicit
    home = os.environ.get("JAVA_HOME")
    if home:
        candidate = pathlib.Path(home) / "bin" / ("javac.exe" if os.name == "nt" else "javac")
        if candidate.exists():
            return str(candidate)
    found = shutil.which("javac")
    if not found:
        sys.exit("javac not found: pass --javac or set JAVA_HOME")
    return found


def write_header(name: str, data: bytes) -> None:
    lines = [
        "#pragma once",
        f"// Generated by tools/build_java.py from java/src/{name}.java. Do not edit.",
        "",
        f"static const unsigned char k{name}Bytes[] = {{",
    ]
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in data[i : i + 16]) + ",")
    lines.append("};")
    lines.append(f"static const unsigned int k{name}Size = {len(data)};")
    lines.append("")
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / f"{name}.h").write_text("\n".join(lines), encoding="utf-8", newline="\r\n")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--javac")
    args = parser.parse_args()
    javac = find_javac(args.javac)

    sources = sorted(SRC.glob("*.java"))
    stubs = sorted(STUBS.rglob("*.java"))
    with tempfile.TemporaryDirectory() as tmp:
        stub_out = pathlib.Path(tmp) / "stubs"
        cls_out = pathlib.Path(tmp) / "classes"
        stub_out.mkdir()
        cls_out.mkdir()
        subprocess.run([javac, "--release", "8", "-nowarn", "-d", str(stub_out), *map(str, stubs)], check=True)
        subprocess.run([javac, "--release", "8", "-g:none", "-cp", str(stub_out), "-d", str(cls_out), *map(str, sources)],
                       check=True)
        for src in sources:
            name = src.stem
            data = (cls_out / f"{name}.class").read_bytes()
            write_header(name, data)
            print(f"{name}: {len(data)} bytes")


if __name__ == "__main__":
    main()
